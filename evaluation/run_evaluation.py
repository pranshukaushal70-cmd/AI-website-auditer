#!/usr/bin/env python3
"""Run the offline detector evaluation and write (or check) the results.

    python evaluation/run_evaluation.py            # writes evaluation/results/v1/results.{json,md}
    python evaluation/run_evaluation.py --check    # re-runs and fails if results differ from the committed ones

Every number in results.md is rendered from results.json, which is produced by this run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import harness  # noqa: E402

RESULTS_DIR = Path(__file__).resolve().parent / "results"


def _fmt(value) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def render_markdown(result: dict) -> str:
    ds = result["dataset"]
    lines = [
        f"# Detector evaluation results — dataset {ds['version']}",
        "",
        "Generated by `python evaluation/run_evaluation.py` from `results.json`; do not edit by hand.",
        "",
        f"- Dataset: {ds['cases']} cases, {ds['labels']} labels, reference year {ds['current_year']}, sha256 `{ds['sha256'][:16]}…`",
        f"- Engine: marketplace {result['engine_manifest_version']}; harness {result['harness']}",
        f"- Abstentions (detector returned no pass/fail verdict): {result['abstentions']}",
        "",
        "| Detector | Labelled (+/−) | TP | FP | FN | TN | Precision | Recall | F1 | FPR |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, d in result["per_detector"].items():
        lines.append(f"| `{name}` | {d['labelled']} ({d['positives']}/{d['negatives']}) | {d['tp']} | {d['fp']} | {d['fn']} | {d['tn']} | "
                     f"{_fmt(d['precision'])} | {_fmt(d['recall'])} | {_fmt(d['f1'])} | {_fmt(d['false_positive_rate'])} |")
    m = result["micro"]
    lines += [f"| **micro (all labels)** | {result['dataset']['labels']} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} | "
              f"{_fmt(m['precision'])} | {_fmt(m['recall'])} | {_fmt(m['f1'])} | {_fmt(m['false_positive_rate'])} |",
              "", f"Macro-averaged F1 over detectors: {_fmt(result['macro_f1'])}.", "",
              "## By case kind", "",
              "| Kind | Labels | TP | FP | FN | TN | Precision | Recall | F1 |", "|---|---|---|---|---|---|---|---|---|"]
    for kind, d in result["per_kind"].items():
        lines.append(f"| {kind} | {d['labelled']} | {d['tp']} | {d['fp']} | {d['fn']} | {d['tn']} | "
                     f"{_fmt(d['precision'])} | {_fmt(d['recall'])} | {_fmt(d['f1'])} |")
    lines.append("")
    lines += ["## Errors (false positives and false negatives)", ""]
    if not result["errors"]:
        lines.append("None.")
    else:
        lines += ["| Case | Kind | Detector | Expected | Predicted | Label rationale | Engine evidence (truncated) |", "|---|---|---|---|---|---|---|"]
        for e in result["errors"]:
            ev = e["engine_evidence"].replace("|", "\\|")[:160]
            lines.append(f"| `{e['case']}` | {e['kind']} | `{e['detector']}` | {e['expected']} | {e['predicted']} | "
                         f"{e['rationale'].replace('|', '/')} | {ev} |")
    rt = result["runtime"]
    lines += ["", f"Runtime (informational, machine-dependent): median {rt['per_case_seconds_median']} s per case, "
              f"max {rt['per_case_seconds_max']} s; Python {rt['python']} on {rt['platform']}.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", default="v1")
    parser.add_argument("--check", action="store_true", help="compare against committed results instead of writing")
    parser.add_argument("--name", default="results",
                        help="results file stem under evaluation/results/<dataset>/ (default: results). Refuses to overwrite "
                             "an existing file unless the name is 'results'.")
    parser.add_argument("--ablation-mock-headers", action="store_true",
                        help="also run with dict headers (the shape unit-test mocks use) and print what changes; writes nothing")
    args = parser.parse_args(argv)

    result = harness.evaluate(args.dataset)
    if args.ablation_mock_headers:
        real_headers = harness._http_headers
        harness._http_headers = lambda url, extra: {"_final_url": url, "_redirect_chain": [], **extra}
        try:
            mock = harness.evaluate(args.dataset)
        finally:
            harness._http_headers = real_headers
        print(f"micro F1: production header type {_fmt(result['micro']['f1'])}, mock dict headers {_fmt(mock['micro']['f1'])}")
        for a, b in zip(result["rows"], mock["rows"], strict=True):
            if a["outcome"] != b["outcome"]:
                print(f"  {a['case']} / {a['detector']}: {a['outcome']} -> {b['outcome']} with mock headers")
        return 0
    out_dir = RESULTS_DIR / args.dataset
    json_path = out_dir / f"{args.name}.json"
    if not args.check and args.name != "results" and json_path.exists():
        print(f"Refusing to overwrite {json_path}; choose a new --name.", file=sys.stderr)
        return 2
    if args.check:
        if not json_path.is_file():
            print(f"No committed results at {json_path}", file=sys.stderr)
            return 2
        committed = json.loads(json_path.read_text(encoding="utf-8"))
        if harness.deterministic_view(committed) != harness.deterministic_view(result):
            print("Evaluation results differ from the committed results. Re-run without --check and review the diff.", file=sys.stderr)
            return 1
        print(f"Reproducible: results match {json_path.relative_to(harness.ROOT).as_posix()} "
              f"(micro F1 {_fmt(result['micro']['f1'])}, {result['dataset']['labels']} labels).")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out_dir / f"{args.name}.md").write_text(render_markdown(result), encoding="utf-8")
    m = result["micro"]
    print(f"{result['dataset']['labels']} labels over {result['dataset']['cases']} cases: "
          f"micro P={_fmt(m['precision'])} R={_fmt(m['recall'])} F1={_fmt(m['f1'])}; "
          f"{len(result['errors'])} error(s), {result['abstentions']} abstention(s). Wrote {out_dir.relative_to(harness.ROOT).as_posix()}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
